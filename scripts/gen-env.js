import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";





const root = new URL("..", import.meta.url);
const envPath = join(fileURLToPath(root), ".env");
const outPath = join(fileURLToPath(root), "src", "env.js");

const KEYS = ["GEMINI_API_KEY", "GROQ_API_KEY", "PROJECT_ARES_API_KEY", "CALLMISSED_API_KEY", "CEREBRAS_API_KEY", "MISTRAL_API_KEY", "DISCORD_CLIENT_ID", "GOOGLE_CLIENT_ID", "OBJECTFLIX_API_BASE_URL", "OBJECTFLIX_AI_PROVIDER", "ARG_SECRET"];

const values = {};
for (const key of KEYS) values[key] = "";

try {
  const text = readFileSync(envPath, "utf8");
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    if (KEYS.includes(key)) values[key] = trimmed.slice(eq + 1).trim();
  }
} catch {
  
}



for (const key of KEYS) {
  const v = process.env[key];
  if (v !== undefined && v !== "") values[key] = v;
}

const body = `// GENERATED by scripts/gen-env.js - do not edit. This file is gitignored.
window.__OBJECTFLIX_ENV__ = Object.freeze(${JSON.stringify(values, null, 2)});
`;

writeFileSync(outPath, body, "utf8");
const empty = KEYS.every((k) => !values[k]);
console.log(empty ? "src/env.js written (all values empty — did you create .env?)" : "src/env.js written from .env");
